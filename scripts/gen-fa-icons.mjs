// Lists every free Font Awesome icon (one "style:name" string each) for the
// bookmark icon explorer. Run: node scripts/gen-fa-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const pkgDir = path.join(root, '..', 'node_modules', '@fortawesome', 'fontawesome-free');
const pkg = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));

const styles = ['solid', 'regular', 'brands'];
const out = [];
for (const style of styles) {
  const dir = path.join(pkgDir, 'svgs', style);
  for (const file of fs.readdirSync(dir)) {
    if (!file.endsWith('.svg')) continue;
    out.push(`fa-${style}:${file.slice(0, -4)}`);
  }
}
out.sort((a, b) => a.split(':')[1].localeCompare(b.split(':')[1]));

const body =
  `// GENERATED by scripts/gen-fa-icons.mjs — do not edit. Source: @fortawesome/fontawesome-free@${pkg.version}.\n` +
  `export const FA_VERSION = '${pkg.version}';\n` +
  `export const FA_RAW: string[] = [\n${out.map((s) => `  '${s}',`).join('\n')}\n];\n`;
fs.writeFileSync(path.join(root, '..', 'src', 'faRaw.ts'), body);
console.log(`faRaw.ts: ${out.length} icons (Font Awesome ${pkg.version})`);
