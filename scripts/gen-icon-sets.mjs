// Generates bundled icon-library data + minimal font CSS for the extra sets:
// Tabler (outline SVG), Streamline (Iconify SVG), Iconoir (regular/solid SVG),
// Lineicons (Iconify SVG), Boxicons (font), Mingcute (font).
// Rerun after `npm update`: node scripts/gen-icon-sets.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const nm = join(root, 'node_modules');
const read = (p) => readFileSync(p, 'utf8');
const pkg = (n) => JSON.parse(read(join(nm, n, 'package.json')));
const versions = {
  tabler: pkg('@tabler/icons').version,
  streamline: pkg('@iconify-json/streamline').version,
  iconoir: pkg('iconoir').version,
  lineicons: pkg('@iconify-json/lineicons').version,
  boxicons: pkg('boxicons').version,
  mingcute: pkg('mingcute_icon').version,
};
console.log('versions:', JSON.stringify(versions));

// Collapse inter-tag whitespace (these sets are path/shape-only, no <text>).
const squeeze = (s) => s.replace(/>\s+</g, '><').trim();

// ---- Tabler (outline SVG, 24px stroke) ----
const tablerMeta = JSON.parse(read(join(nm, '@tabler/icons/icons.json')));
const tablerDir = join(nm, '@tabler/icons/icons/outline');
const tablerSigs = new Set();
let tablerStripped = 0;
const TABLER = readdirSync(tablerDir).filter((f) => f.endsWith('.svg')).map((f) => {
  const name = f.slice(0, -4);
  const raw = read(join(tablerDir, f));
  const open = raw.match(/<svg[\s\S]*?>/)[0].replace(/\s+class="[^"]*"/, '').replace(/\s+/g, ' ');
  tablerSigs.add(open);
  let inner = raw.replace(/<svg[\s\S]*?>/, '').replace(/<\/svg>\s*$/, '');
  const noop = /<path\s+stroke="none"\s+d="M0 0h24v24H0z"\s+fill="none"\s*\/>/g;
  if (noop.test(inner)) tablerStripped++;
  inner = squeeze(inner.replace(noop, ''));
  const tags = (tablerMeta[name] && tablerMeta[name].tags) || [];
  return [name, [name, ...tags].join(' '), inner, 24, 24];
}).sort((a, b) => (a[0] < b[0] ? -1 : 1));
console.log('tabler:', TABLER.length, 'root-signatures:', tablerSigs.size, 'noop-stripped:', tablerStripped);
if (tablerSigs.size !== 1) { console.log([...tablerSigs]); throw new Error('tabler root attrs vary'); }

// ---- Iconify-JSON sets (Streamline, Lineicons) ----
function iconifySet(pkgName) {
  const j = JSON.parse(read(join(nm, pkgName, 'icons.json')));
  const dw = j.width || 24, dh = j.height || 24;
  const aliasOf = {};
  for (const [a, v] of Object.entries(j.aliases || {})) {
    if (v && j.icons[v.parent]) (aliasOf[v.parent] = aliasOf[v.parent] || []).push(a);
  }
  return Object.keys(j.icons).map((name) => {
    const e = j.icons[name];
    return [name, [name, ...(aliasOf[name] || [])].join(' '), squeeze(e.body), e.width || dw, e.height || dh];
  }).sort((a, b) => (a[0] < b[0] ? -1 : 1));
}
const STREAMLINE = iconifySet('@iconify-json/streamline');
const LINEICONS = iconifySet('@iconify-json/lineicons');
console.log('streamline:', STREAMLINE.length, 'lineicons:', LINEICONS.length);

// ---- Iconoir (regular + solid SVG) ----
function iconoirSet(style) {
  const dir = join(nm, 'iconoir/icons', style);
  const sigs = new Set();
  const out = readdirSync(dir).filter((f) => f.endsWith('.svg')).map((f) => {
    const name = f.slice(0, -4);
    const raw = read(join(dir, f));
    const open = raw.match(/<svg[\s\S]*?>/)[0];
    const vb = (open.match(/viewBox="([^"]*)"/) || [])[1];
    const sw = (open.match(/stroke-width="([^"]*)"/) || [])[1];
    const fill = (open.match(/\sfill="([^"]*)"/) || [])[1];
    sigs.add(`${vb}|${sw}|${fill}`);
    const inner = squeeze(raw.replace(/<svg[\s\S]*?>/, '').replace(/<\/svg>\s*$/, ''));
    return [name, name, inner, sw || ''];
  }).sort((a, b) => (a[0] < b[0] ? -1 : 1));
  console.log(`iconoir-${style}:`, out.length, 'sigs:', [...sigs].join(' ; '));
  return out;
}
const ICONOIR_REGULAR = iconoirSet('regular');
const ICONOIR_SOLID = iconoirSet('solid');

// ---- Font sets: Boxicons + Mingcute (names + minimal CSS) ----
function fontSet(cssPath, re) {
  const css = read(cssPath);
  const names = [];
  const rules = [];
  let m;
  while ((m = re.exec(css))) { names.push(m[1]); rules.push(`.${m[1]}:before{content:"${m[2]}"}`); }
  return { names: names.sort(), rules, css };
}
const bx = fontSet(join(nm, 'boxicons/css/boxicons.css'), /\.((?:bx|bxs|bxl)-[a-z0-9-]+):before\s*\{[^}]*?content:\s*['"]([^'"]+)['"]/g);
const bxBase = bx.css.match(/\.bx\s*\{[^}]*\}/)[0].replace(/\s+/g, ' ');
const mg = fontSet(join(nm, 'mingcute_icon/font/Mingcute.css'), /\.((?:mgc_)[a-z0-9_]+):before\s*\{[^}]*?content:\s*['"]([^'"]+)['"]/g);
const mgBase = mg.css.match(/\[class\^="mgc_"\][\s\S]*?\}/)[0].replace(/\s+/g, ' ');
console.log('boxicons:', bx.names.length, 'mingcute:', mg.names.length);

const ts = `// GENERATED by scripts/gen-icon-sets.mjs — DO NOT EDIT.
// Rerun after \`npm update\`: node scripts/gen-icon-sets.mjs
export const SETS_VERSIONS = ${JSON.stringify(versions)} as const;
// SvgRec: [name, searchText, innerMarkup, width, height]
export type SvgRec = [name: string, search: string, body: string, w: number, h: number];
export const TABLER: SvgRec[] = ${JSON.stringify(TABLER)};
export const STREAMLINE: SvgRec[] = ${JSON.stringify(STREAMLINE)};
export const LINEICONS: SvgRec[] = ${JSON.stringify(LINEICONS)};
// IconoirRec: [name, searchText, innerMarkup, strokeWidth|'']
export type IconoirRec = [name: string, search: string, body: string, sw: string];
export const ICONOIR_REGULAR: IconoirRec[] = ${JSON.stringify(ICONOIR_REGULAR)};
export const ICONOIR_SOLID: IconoirRec[] = ${JSON.stringify(ICONOIR_SOLID)};
export const BOXICONS: string[] = ${JSON.stringify(bx.names)};
export const MINGCUTE: string[] = ${JSON.stringify(mg.names)};
`;
writeFileSync(join(root, 'src/setsData.ts'), ts);

const css = `/* GENERATED by scripts/gen-icon-sets.mjs — DO NOT EDIT. Minimal @font-face (single modern format) + icon rules. */
@font-face{font-family:'boxicons';src:url('../node_modules/boxicons/fonts/boxicons.woff2') format('woff2');font-weight:normal;font-style:normal;font-display:block}
${bxBase.replace('.bx', '.bx,.bxs,.bxl')}
${bx.rules.join('')}
@font-face{font-family:'MingCute';src:url('../node_modules/mingcute_icon/font/MingCute.woff') format('woff');font-weight:normal;font-style:normal;font-display:block}
${mgBase}
${mg.rules.join('')}
`;
writeFileSync(join(root, 'src/setsFonts.css'), css);
console.log('wrote src/setsData.ts + src/setsFonts.css');
